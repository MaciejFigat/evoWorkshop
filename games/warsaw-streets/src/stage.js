/* Stage rendering: scrolling backdrop picture + generated street paving.

   The concept panoramas only contain a thin strip of pavement, so the picture is drawn at
   `bgH` px and the walkable ground below it is generated by stretching the picture's last rows
   (keeps the lamp / neon colour streaks) and overlaying perspective paving joints. All
   characters stand on one ground plane: floorTop..floorBottom is the allowed foot-y range. */
(function () {
  'use strict';
  const WS = window.WS;

  class Stage {
    constructor(def, src) {
      this.def = def;
      this.bgH = def.bgH;
      // Cut the panel out of the strips image and scale it to the picture height. Done here at
      // load time (canvas drawImage), so no pre-generated stage images are needed.
      const [py, ph] = def.panel;
      const w = Math.round(src.width * def.bgH / ph);
      const pic = document.createElement('canvas');
      pic.width = w; pic.height = def.bgH;
      const pg = pic.getContext('2d');
      pg.imageSmoothingEnabled = true;
      pg.imageSmoothingQuality = 'high';
      pg.drawImage(src, 0, py, src.width, ph, 0, 0, w, def.bgH);
      const img = this.img = pic;
      this.width = w;
      this.floorTop = def.floorTop; this.floorBottom = def.floorBottom;
      this.maxCam = this.width - WS.W;
      // cache the generated floor strip (one image the width of the picture)
      const h = WS.H - this.bgH;
      const c = document.createElement('canvas');
      c.width = this.width; c.height = h;
      const g = c.getContext('2d');
      g.imageSmoothingEnabled = false;
      g.drawImage(img, 0, this.bgH - 3, this.width, 3, 0, 0, this.width, h);
      // darken towards the viewer, soften the stretch with a gradient
      const grad = g.createLinearGradient(0, 0, 0, h);
      grad.addColorStop(0, 'rgba(10,8,24,0.15)');
      grad.addColorStop(1, 'rgba(6,4,16,0.55)');
      g.fillStyle = grad; g.fillRect(0, 0, this.width, h);
      // paving: horizontal joints getting wider apart towards the camera, brick-offset verticals
      g.fillStyle = 'rgba(0,0,0,0.28)';
      const rows = [2, 7, 14, 23, 34];
      for (const r of rows) if (r < h) g.fillRect(0, r, this.width, 1);
      g.fillStyle = 'rgba(0,0,0,0.20)';
      rows.push(h);
      for (let i = 0; i < rows.length - 1; i++) {
        const y0 = rows[i], y1 = rows[i + 1];
        const spacing = 10 + i * 8;
        const off = (i % 2) * (spacing / 2);
        for (let x = -off; x < this.width; x += spacing) g.fillRect(Math.round(x), y0, 1, y1 - y0);
      }
      this.floor = c;
    }

    clampY(y) { return WS.clamp(y, this.floorTop, this.floorBottom); }

    draw(ctx, camX) {
      camX = Math.round(camX);
      ctx.drawImage(this.img, camX, 0, WS.W, this.bgH, 0, 0, WS.W, this.bgH);
      ctx.drawImage(this.floor, camX, 0, WS.W, this.floor.height, 0, this.bgH, WS.W, this.floor.height);
    }
  }

  WS.Stage = Stage;
})();
